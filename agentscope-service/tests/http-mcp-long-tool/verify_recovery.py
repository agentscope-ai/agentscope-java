"""Restart the actual owner of a real long-tool acceptance, retaining failure evidence."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import subprocess
import sys
import time
import urllib.request
import uuid


def runtime_events(logs, session):
    events = []
    for line in logs.splitlines():
        if 'managed_runtime ' not in line:
            continue
        try:
            event = json.loads(line.split('managed_runtime ', 1)[1])
        except ValueError:
            continue
        if event.get('session_id') == session:
            events.append(event)
    return sorted(events, key=lambda event: event['timestamp'])


def run(args):
    config = json.loads(Path(__file__).with_name('cluster-test.json').read_text())
    args.out_dir.mkdir(parents=True, exist_ok=False)
    args.out_dir.chmod(0o700)
    token = json.loads(args.token_file.read_text())['token']
    namespace = config['kubernetesNamespace']
    kubectl = ['kubectl', '--kubeconfig', str(args.kubeconfig), '-n', namespace]
    report = {'passed': False, 'component': args.component, 'namespace': namespace,
              'startedAt': datetime.now(timezone.utc).isoformat(), 'seconds': args.seconds}

    def save(name, value):
        path = args.out_dir / name
        path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')
        path.chmod(0o600)

    def kube(*command):
        return json.loads(subprocess.check_output(kubectl + list(command) + ['-o', 'json']))

    def api(path, body=None):
        headers = {'Authorization': 'Bearer ' + token, 'Content-Type': 'application/json',
                   'X-Managed-Agents-Tenant': 'default', 'X-Managed-Agents-Namespace': 'default',
                   'Idempotency-Key': 'ha-recovery-' + str(uuid.uuid4())}
        request = urllib.request.Request(config['baseUrl'] + path,
            None if body is None else json.dumps(body).encode(), headers)
        with urllib.request.urlopen(request, timeout=40) as response:
            return json.load(response)

    def facts(session):
        # Session IDs are UUIDs generated by the server; reject anything else before using SQL.
        session = str(uuid.UUID(session))
        sql = "SELECT json_build_object('executions',(SELECT json_agg(json_build_object(" \
            "'task_id',task_id,'execution_id',execution_id,'tool_name',tool_name,'status',status," \
            "'owner_generation',owner_generation,'has_result',result IS NOT NULL)) FROM ma.hands_execution" \
            " WHERE session_id='" + session + "'),'turns',(SELECT json_agg(json_build_object(" \
            "'turn_id',turn_id,'status',status,'admission_sequence',admission_sequence," \
            "'execution_epoch',execution_epoch)) FROM ma.turn WHERE scope_key=(SELECT scope_key" \
            " FROM ma.session WHERE session_id='" + session + "')),'suspensions',(SELECT json_agg(" \
            "json_build_object('turn_id',s.turn_id,'status',s.status)) FROM ma.turn_suspension s" \
            " WHERE s.scope_key=(SELECT scope_key FROM ma.session WHERE session_id='" + session + "')));"
        return json.loads(subprocess.check_output(kubectl + ['exec', 'postgres-0', '--', 'sh', '-ec',
            'PGHOST=127.0.0.1 exec psql -X -A -t -v ON_ERROR_STOP=1 -c "$1"', 'psql', sql], text=True))

    def logs(component, session):
        events = []
        pods = kube('get', 'pods', '-l', 'app.kubernetes.io/component=' + component)
        for pod in pods['items']:
            if pod['metadata'].get('deletionTimestamp') or not any(
                    'running' in c.get('state', {}) for c in pod['status'].get('containerStatuses', [])):
                continue
            output = subprocess.check_output(kubectl + ['logs', pod['metadata']['name'],
                '-c', component, '--tail=-1', '--request-timeout=30s'], text=True)
            events.extend(runtime_events(output, session))
        return sorted(events, key=lambda event: event['timestamp'])

    def physical(marker):
        output = subprocess.check_output(kubectl + ['logs', '-l', 'app=managed-agents-long-tool-mcp',
            '--tail=-1', '--max-log-requests=4'], text=True)
        events = []
        for line in output.splitlines():
            try:
                event = json.loads(line)
            except ValueError:
                continue
            if event.get('marker') == marker:
                events.append(event)
        return events

    deployments = kube('get', 'deployments', '-l', 'app.kubernetes.io/instance=ma')
    assert len(deployments['items']) == 5
    assert all(d['spec']['replicas'] >= 2 and d['status'].get('readyReplicas', 0) >= 2
               for d in deployments['items']), 'Start with all five components at two ready replicas'
    save('deployments-before.json', deployments)
    session = api('/v1/sessions', {'agent': config['agentId'], 'environment_id': config['environmentId'],
        'title': args.component + ' owner Pod restart acceptance', 'metadata': {'verification': 'ha-recovery'}})
    assert session['id'] != config['preparedSessionId']
    save('session.json', session)
    report['sessionId'] = session['id']
    save('report.json', report)
    command = [sys.executable, '-u', str(Path(__file__).with_name('verify_session.py')),
        '--session', session['id'], '--token-file', str(args.token_file), '--out-dir', str(args.out_dir / 'acceptance'),
        '--kubeconfig', str(args.kubeconfig), '--seconds', str(args.seconds)]
    log_path = args.out_dir / 'acceptance.log'
    child = None
    try:
        with log_path.open('w') as stream:
            os.chmod(log_path, 0o600)
            child = subprocess.Popen(command, stdout=stream, stderr=subprocess.STDOUT)
        deadline = time.monotonic() + 180
        state_path = args.out_dir / 'acceptance/report.json'
        while time.monotonic() < deadline:
            assert child.poll() is None, 'Acceptance exited before fault injection; inspect acceptance.log'
            if state_path.exists():
                try:
                    state = json.loads(state_path.read_text())
                except ValueError:
                    time.sleep(1)
                    continue
                if any(s['t1'] == 'waiting_tool' and s['t2'] == 'accepted' for s in state['states']):
                    invocation = physical(state['marker'])
                    started = [e for e in invocation if e['event'] == 'long_wait.started']
                    assert len(started) <= 1, 'Duplicate physical start before fault injection'
                    if started:
                        events = logs(args.component, session['id'])
                        if args.component == 'tool-worker':
                            owners = [e for e in events if e['event'] == 'tool_worker.tool.start.requested'
                                      and e.get('turn_id') == state['turn1'] and e.get('tool_name') == 'mcp.call'
                                      and e.get('mode') == 'first_launch']
                        else:
                            owners = [e for e in events if e['event'] == 'harness_runtime.execution.started'
                                      and e.get('turn_id') == state['turn1']]
                        if owners:
                            break
            time.sleep(1)
        else:
            raise AssertionError('No actual in-flight owner found before the injection deadline')
        assert not any(e['event'] == 'long_wait.completed' for e in invocation), 'Tool already finished'
        owner = owners[-1]
        pod = kube('get', 'pod', owner['host'])
        assert pod['metadata']['labels']['app.kubernetes.io/component'] == args.component
        assert pod['metadata']['labels']['app.kubernetes.io/instance'] == 'ma'
        peers = kube('get', 'pods', '-l', 'app.kubernetes.io/component=' + args.component)
        assert any(p['metadata']['uid'] != pod['metadata']['uid'] and
                   any(c['type'] == 'Ready' and c['status'] == 'True' for c in p['status'].get('conditions', []))
                   for p in peers['items']), 'Keep a healthy peer during fault injection'
        save('owner-pod-before.json', pod)
        save('owner-log-before.json', events)
        save('facts-before.json', facts(session['id']))
        report.update(turn1=state['turn1'], turn2=state['turn2'], marker=state['marker'],
            deletedPod=owner['host'], deletedPodUid=pod['metadata']['uid'],
            faultAt=datetime.now(timezone.utc).isoformat(), fault='owner Pod deletion, one-second termination grace')
        save('report.json', report)
        print('RESTART', args.component, owner['host'], session['id'], flush=True)
        subprocess.run(kubectl + ['delete', 'pod', owner['host'], '--grace-period=1', '--wait=false'], check=True)
        # Existing acceptance has a bounded 90s + 240s deadline and checks both final outputs.
        child.wait(timeout=args.seconds + 300)
        report['acceptanceExitCode'] = child.returncode
        report['acceptance'] = json.loads(state_path.read_text())
        save('facts-after.json', facts(session['id']))
        invocation = physical(state['marker'])
        save('physical-invocations.json', invocation)
        starts = [e for e in invocation if e['event'] == 'long_wait.started']
        finished = [e for e in invocation if e['event'] == 'long_wait.completed']
        report.update(physicalStarts=len(starts), physicalCompletions=len(finished), noDuplicatePhysicalCall=len(starts) == 1)
        events = logs(args.component, session['id'])
        save('recovery-log-after.json', events)
        report['observedHostsAfterFault'] = sorted({e['host'] for e in events if e['timestamp'] > report['faultAt']})
        if args.component == 'agent-harness-runtime':
            report['recoveredExecutionHosts'] = sorted({e['host'] for e in events
                if e['event'] == 'harness_runtime.execution.started' and e.get('turn_id') == state['turn1']
                and e['host'] != report['deletedPod'] and e['timestamp'] > report['faultAt']})
        else:
            report['remoteResultRecovery'] = [e for e in events
                if e['event'] == 'tool_worker.mcp.execution.queried' and e.get('turn_id') == state['turn1']
                and e.get('external_state') == 'SUCCEEDED' and e['host'] != report['deletedPod']
                and e['timestamp'] > report['faultAt']]
        wait = subprocess.run(kubectl + ['rollout', 'status', 'deployment/ma-managed-agents-' + args.component,
            '--timeout=300s'], capture_output=True, text=True)
        report['replicasRestored'] = wait.returncode == 0
        save('deployments-after.json', kube('get', 'deployments', '-l', 'app.kubernetes.io/instance=ma'))
        report['passed'] = child.returncode == 0 and report['acceptance'].get('passed') is True \
            and len(starts) == len(finished) == 1 and report['replicasRestored']
        if args.component == 'agent-harness-runtime':
            report['passed'] = report['passed'] and bool(report['recoveredExecutionHosts'])
        else:
            report['passed'] = report['passed'] and bool(report['remoteResultRecovery'])
        save('report.json', report)
        print('PASS' if report['passed'] else 'FAIL', args.component,
              'physical starts/completions', len(starts), len(finished), 'report', args.out_dir / 'report.json', flush=True)
        return 0 if report['passed'] else 1
    except BaseException as error:
        report['error'] = str(error)
        save('report.json', report)
        raise
    finally:
        if child is not None and child.poll() is None:
            child.terminate()
            child.wait(timeout=10)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--component', choices=['agent-harness-runtime', 'tool-worker'], required=True)
    parser.add_argument('--token-file', type=Path, required=True)
    parser.add_argument('--kubeconfig', type=Path, required=True)
    parser.add_argument('--out-dir', type=Path, required=True, help='New private output directory')
    parser.add_argument('--seconds', type=int, default=90, choices=range(60, 181), metavar='60..180')
    sys.exit(run(parser.parse_args()))
