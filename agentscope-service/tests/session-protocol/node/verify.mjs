import Anthropic from '@anthropic-ai/sdk';
import assert from 'node:assert/strict';
const [baseURL, apiKey, expected] = process.argv.slice(2);
const client = new Anthropic({ baseURL, apiKey, maxRetries: 0 });
const session = await client.beta.sessions.create({ agent: 'agent', environment_id: 'environment' });
assert.equal(session.id, expected);
assert.equal(session.agent.execution_identity.type, 'service_account');
assert.equal(session.agent.tools[0].type, 'agent_toolset_20260401');
assert.equal(session.agent.tools[0].default_config.enabled, false);
assert.equal(session.agent.tools[1].default_config.permission_policy.type, 'always_allow');
assert.equal(session.agent.mcp_servers[0].name, 'longwait');
const retrieved = await client.beta.sessions.retrieve(session.id);
assert.equal(retrieved.status, 'idle');
const sent = await client.beta.sessions.events.send(session.id, { events: [{ type: 'user.message', content: [{ type: 'text', text: 'official TypeScript SDK' }] }] });
assert.equal(sent.data.length, 1);
assert.equal(sent.data[0].type, 'user.message');
const events = await client.beta.sessions.events.list(session.id, { limit: 1 });
assert.equal(events.data[0].id, sent.data[0].id);
assert.equal(events.data[0].processed_at, null);
console.log('Official TypeScript SDK 0.135.0: create/retrieve/send/list validated');
